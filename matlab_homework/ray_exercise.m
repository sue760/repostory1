clc;
clear;
close all;

% ==================== STEP 1: 加载参数 ====================
disp('请按照PPT上的数值依次输入参数（不带单位）：');

% 提示：PPT给的直径是20nm，所以输入半径时请输入 10
a = input('1. 球体半径 a (nm): '); 
lambda = input('2. 真空波长 lambda (nm): '); 
ns = input('3. 球体折射率 ns: '); 
nb = input('4. 背景折射率 nb: '); 
rhos = input('5. 球体比重 rhos (g/cm^3): '); 
rhob = input('6. 背景比重 rhob (g/cm^3): '); 
Cwt = input('7. 重量浓度 Cwt: '); 

% ==================== 单位换算 ====================
% 瑞利散射公式通常使用国际单位制（米），所以需要把纳米转换成米
a_m = a * 1e-9;
lambda_m = lambda * 1e-9;

% ==================== 计算散射效率 Qs ====================
% 1. 相对折射率 m
m = ns / nb;

% 2. 尺寸参数 x
x = 2 * pi * a_m * nb / lambda_m;

% 3. 根据瑞利散射公式计算散射效率 Qs
% 公式：Qs = (8/3) * x^4 * |(m^2 - 1) / (m^2 + 2)|^2
Qs = (8/3) * x^4 * abs((m^2 - 1) / (m^2 + 2))^2;

% ==================== 计算散射系数 mus ====================
% 1. 计算单个颗粒的几何截面积和散射截面
sigma_geom = pi * a_m^2;        % 几何截面
sigma_scat = Qs * sigma_geom;   % 散射截面

% 2. 计算颗粒数密度 N（单位体积内的颗粒个数）
% 重量浓度 Cwt = (颗粒总质量) / (背景质量) = (N * rhos * Vp) / rhob
% 所以 N = (Cwt * rhob) / (rhos * Vp)
Vp = (4/3) * pi * a_m^3;        % 单个球体体积
N = (Cwt * rhob) / (rhos * Vp);

% 3. 计算散射系数 mus = 数密度 * 散射截面
mus = N * sigma_scat;

% ==================== 输出结果 ====================
fprintf('\n========== 计算结果 ==========\n');
fprintf('相对折射率 m = %.4f\n', m);
fprintf('尺寸参数 x = %.4f\n', x);
fprintf('散射效率 Qs = %.4e\n', Qs);
fprintf('散射系数 mus = %.4e m^-1\n', mus);
fprintf('==============================\n');